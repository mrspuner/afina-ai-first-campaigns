import { type Page } from "@playwright/test";

/**
 * Принудительно отключает онлайн AI-оркестратор ДО того, как приложение
 * смонтируется, делая regex/офлайн-путь единственным для этого теста —
 * независимо от того, настроен ли на машине реальный ключ провайдера
 * (`DEEPSEEK_API_KEY`/`GOOGLE_GENERATIVE_AI_API_KEY` в `.env.local`).
 *
 * Почему это нужно: `isAiParserEnabled()` (src/state/dev-config.ts) по
 * умолчанию ВКЛЮЧЁН (auto-режим — «AI, когда есть ключ»). Комментарий там же
 * документирует расчёт на «нет ключа → бит-в-бит офлайн-путь», но это условие
 * держится на отсутствии `.env.local` — ничем не защищено от локальной
 * машины разработчика, где ключ реально настроен (для ручной разработки AI-
 * фич). Тест, который печатает произвольный текст/команду ноды и ждёт
 * КОНКРЕТНУЮ офлайн-реплику (regex-путь), гонится с асинхронной пробой
 * `fetchAssistAvailability()` — на машине с валидным ключом эта проба рано
 * или поздно резолвится в true, и композер начинает отдавать ввод реальному
 * оркестратору вместо regex-пути, так что ожидаемый текст никогда не
 * появляется (это не связано с содержимым графа/доменов — тайминг гонки
 * зависит только от того, успела ли проба резолвиться до Enter).
 *
 * Записываем "off" в тот же ключ, что и дев-панель («выключить AI» тумблер,
 * задуман как ручной QA-инструмент) — здесь тот же переключатель используется
 * для детерминизма e2e, а не только для ручной проверки regex-пути.
 *
 * MUST be called BEFORE `page.goto(...)`.
 */
export async function forceOfflineAi(page: Page): Promise<void> {
  await page.addInitScript(() => {
    window.localStorage.setItem("afina.dev.aiParser", "off");
  });
}
